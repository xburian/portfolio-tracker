import React, { useMemo } from 'react';
import { Flame, ShieldCheck, TrendingUp, Sparkles, ArrowRight, Clock, Coffee } from 'lucide-react';
import { usePortfolioStore } from '@/lib/stores/usePortfolioStore';
import { useBudgetStore } from '@/lib/stores/useBudgetStore';
import { usePreferencesStore } from '@/lib/stores/usePreferencesStore';
import { FireService } from '@/lib/services/fireService';
import { MoneyDisplay } from '@/components/common/MoneyDisplay';

export const FIREStatusBar: React.FC = () => {
  const holdings = usePortfolioStore((s) => s.holdings);
  const accounts = usePortfolioStore((s) => s.accounts);
  const getCashflowSnapshot = useBudgetStore((s) => s.getCashflowSnapshot);
  const setActiveTab = usePreferencesStore((s) => s.setActiveTab);

  const cashflow = getCashflowSnapshot();

  const totalPortfolioValue = useMemo(() => {
    let total = 0;
    for (const h of holdings) {
      total += (h.currentPrice || h.buyPrice || 0) * (h.totalQuantity || 0);
    }
    for (const a of accounts) {
      for (const amt of Object.values(a.cashBalances || {})) {
        total += amt || 0;
      }
    }
    return total;
  }, [holdings, accounts]);

  const totalCash = useMemo(() => {
    let cash = 0;
    for (const a of accounts) {
      for (const amt of Object.values(a.cashBalances || {})) {
        cash += amt || 0;
      }
    }
    return cash;
  }, [accounts]);

  const essentialExp = cashflow.essentialExpensesCZK > 0 ? cashflow.essentialExpensesCZK : 30000;
  const totalExp = cashflow.totalMonthlyExpensesCZK > 0 ? cashflow.totalMonthlyExpensesCZK : 50000;
  const monthlyDCA = cashflow.netInvestableCapacityCZK > 0 ? cashflow.netInvestableCapacityCZK : 25000;

  const fire = useMemo(() => {
    return FireService.calculateComprehensiveFIRE({
      currentPortfolioValue: totalPortfolioValue,
      monthlyDCA,
      annualNominalReturn: 0.08,
      swrAnnualRatePct: 3.5, // 3.5% safe withdrawal rate
      essentialMonthlyExpenses: essentialExp,
      totalMonthlyExpenses: totalExp,
      liquidCashAndSavings: totalCash,
    });
  }, [totalPortfolioValue, monthlyDCA, essentialExp, totalExp, totalCash]);

  if (totalPortfolioValue <= 0) return null;

  const leanPct = fire.tiers.lean.progressPercentage;
  const standardPct = fire.tiers.standard.progressPercentage;

  // Monthly passive income generated by current capital at 3.5% SWR
  const currentPassiveMonthly = Math.round(totalPortfolioValue * (0.035 / 12));
  const expenseCoveredPct = Math.min(100, Math.round((currentPassiveMonthly / totalExp) * 1000) / 10);

  return (
    <div className="p-4 sm:p-5 rounded-2xl bg-gradient-to-r from-slate-900/90 via-slate-900/80 to-indigo-950/40 border border-slate-800/80 backdrop-blur-md shadow-lg flex flex-col lg:flex-row items-start lg:items-center justify-between gap-4">
      {/* 1. Left side: FIRE Status Badge & Progress */}
      <div className="flex items-start sm:items-center gap-3.5">
        <div className="p-2.5 rounded-2xl bg-gradient-to-tr from-rose-500/20 to-amber-500/20 text-rose-400 border border-rose-500/30 shrink-0">
          <Flame className="w-5 h-5" />
        </div>
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <span className="text-sm font-bold text-white tracking-tight">Index finanční svobody (FIRE)</span>
            <span className="px-2 py-0.5 rounded-full bg-rose-500/10 text-rose-300 border border-rose-500/30 text-[10px] font-mono font-bold">
              Standard FIRE: {standardPct.toFixed(1)} %
            </span>
            <span className="px-2 py-0.5 rounded-full bg-cyan-500/10 text-cyan-300 border border-cyan-500/30 text-[10px] font-mono font-bold">
              Lean FIRE: {leanPct.toFixed(1)} %
            </span>
          </div>

          <p className="text-xs text-slate-300 mt-1">
            Vaše portfolio již bezpečně nese <strong className="text-emerald-400">+{currentPassiveMonthly.toLocaleString()} Kč / měsíc</strong> (pokryje <strong className="text-white">{expenseCoveredPct} %</strong> vašeho stávajícího životního stylu).
          </p>
        </div>
      </div>

      {/* 2. Middle & Right: Key KPI pills & Action */}
      <div className="flex flex-wrap items-center gap-3 sm:gap-4 shrink-0 w-full lg:w-auto justify-between lg:justify-end border-t lg:border-t-0 pt-3 lg:pt-0 border-slate-800/60">
        {/* Runway */}
        <div className="flex items-center gap-2 px-3 py-1.5 rounded-xl bg-slate-950/60 border border-slate-800 text-xs font-mono">
          <Clock className="w-3.5 h-3.5 text-emerald-400" />
          <span className="text-slate-400">Polštář:</span>
          <strong className="text-white">{fire.liquidRunway.essentialRunwayMonths} měs. nutných výdajů</strong>
        </div>

        {/* Cíl Standard FIRE datum */}
        <div className="flex items-center gap-2 px-3 py-1.5 rounded-xl bg-slate-950/60 border border-slate-800 text-xs font-mono">
          <Sparkles className="w-3.5 h-3.5 text-indigo-400" />
          <span className="text-slate-400">Plný FIRE:</span>
          <strong className="text-rose-400">{fire.tiers.standard.yearsToFIRE} let ({fire.tiers.standard.fireDate})</strong>
        </div>

        {/* 1-click jump button to FIRE Hub */}
        <button
          onClick={() => setActiveTab('projection')}
          className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl bg-rose-600/20 hover:bg-rose-600/30 text-rose-300 border border-rose-500/40 text-xs font-bold transition-all hover:scale-105 active:scale-95"
        >
          <span>FIRE Hub</span>
          <ArrowRight className="w-3.5 h-3.5" />
        </button>
      </div>
    </div>
  );
};
